create table if not exists public.members (
  device_id text primary key,
  name text not null check (char_length(name) between 2 and 120),
  phone text check (phone ~ '^0[0-9]{9}$'),
  section text not null check (section in (
    'A1','A2','A3','B1','B2','B3','C1','C2',
    'C3','D1','D2','D3','E1','E2','F1','F2'
  )),
  registered_at timestamptz not null default now(),
  app_version text not null default '1.0.0'
);

alter table public.members add column if not exists phone text;

alter table public.members enable row level security;

drop policy if exists "Members may register" on public.members;
create policy "Members may register"
on public.members
for insert
to anon, authenticated
with check (true);

drop policy if exists "Members may update their registration" on public.members;
create policy "Members may update their registration"
on public.members
for update
to anon, authenticated
using (true)
with check (true);

