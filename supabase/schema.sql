create table if not exists public.secretariat_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null check (role in ('SEC', 'VSEC')),
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.secretariat_accounts enable row level security;

drop policy if exists "Secretariat members may read their access" on public.secretariat_accounts;
create policy "Secretariat members may read their access"
on public.secretariat_accounts
for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "Active Secretariat may view members" on public.members;
create policy "Active Secretariat may view members"
on public.members
for select
to authenticated
using (
  exists (
    select 1 from public.secretariat_accounts
    where user_id = auth.uid() and is_active = true
  )
);

create or replace function public.register_member(
  p_device_id text,
  p_name text,
  p_phone text,
  p_section text,
  p_app_version text default '1.0.0'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.members (device_id, name, phone, section, app_version)
  values (p_device_id, p_name, p_phone, p_section, p_app_version)
  on conflict (device_id) do update set
    name = excluded.name,
    phone = excluded.phone,
    section = excluded.section,
    app_version = excluded.app_version;
end;
$$;

revoke all on function public.register_member(text, text, text, text, text)
from public;
grant execute on function public.register_member(text, text, text, text, text)
to anon, authenticated;

create table if not exists public.church_notices (
